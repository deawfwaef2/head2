#!/usr/bin/env python3
"""Project CC0 MakeHuman/MPFB2 facial sculpt targets onto our real head skin.

Regenerate: python3 scripts/build_face_fine_targets.py
Only the small, UV-matched head deltas are written to src/data/faceFineTargets.js;
the original OBJ and target files are fetched to memory, not checked in.

Source: https://github.com/makehumancommunity/mpfb2/tree/3af0cd5a2ffba072e93a34e5f6f494fdc4813ddf/src/mpfb/data
Assets: https://github.com/makehumancommunity/mpfb2/blob/master/LICENSE.ASSETS.md (CC0).
"""
from __future__ import annotations

from collections import defaultdict
from gzip import decompress
import json
from pathlib import Path
import struct
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parent.parent
UPSTREAM = (
    'https://raw.githubusercontent.com/makehumancommunity/mpfb2/'
    '3af0cd5a2ffba072e93a34e5f6f494fdc4813ddf/src/mpfb/data/'
)
# In this head the artist-authored MakeHuman targets use 0.115 metres per
# MakeHuman unit; checked against the pre-existing mouth-angles-up vertex
# deltas (e.g. official 0.053 -> 0.00610 m in the GLB).
METRES_PER_UNIT = 0.115
QUANTIZATION = 100000  # the consumer divides each integer by 1e5 metres
SOURCES = {
    'mouth_scale_horiz_incr': ['mouth/mouth-scale-horiz-incr.target.gz'],
    'mouth_scale_horiz_decr': ['mouth/mouth-scale-horiz-decr.target.gz'],
    'eye_bag_decr': ['eyes/l-eye-bag-decr.target.gz', 'eyes/r-eye-bag-decr.target.gz'],
    'eye_bag_height_decr': [
        'eyes/l-eye-bag-height-decr.target.gz',
        'eyes/r-eye-bag-height-decr.target.gz',
    ],
    'mouth_cupidsbow_decr': ['mouth/mouth-cupidsbow-decr.target.gz'],
    'mouth_lowerlip_middle_up': ['mouth/mouth-lowerlip-middle-up.target.gz'],
}


def download(relpath: str) -> bytes:
    req = Request(UPSTREAM + relpath, headers={'User-Agent': 'Cervix3D-offline-head-asset-builder'})
    with urlopen(req, timeout=40) as response:
        return response.read()


def source_vertex_for_uv(obj_bytes: bytes) -> dict[tuple[float, float], int]:
    texture_coords: list[tuple[float, float]] = []
    by_uv: dict[tuple[float, float], int] = {}
    collisions: set[tuple[float, float]] = set()
    for line in obj_bytes.decode('utf-8').splitlines():
        if line.startswith('vt '):
            _, u, v, *_ = line.split()
            texture_coords.append((float(u), float(v)))
        elif line.startswith('f '):
            for token in line.split()[1:]:
                indices = token.split('/')
                if len(indices) < 2 or not indices[1]:
                    continue
                source_index = int(indices[0]) - 1
                u, v = texture_coords[int(indices[1]) - 1]
                # GLB UV origin is the inverse of OBJ UV origin.
                key = (round(u, 5), round(1 - v, 5))
                previous = by_uv.setdefault(key, source_index)
                if previous != source_index:
                    collisions.add(key)
    for key in collisions:
        by_uv.pop(key, None)
    return by_uv


def glb_head_uvs(glb_bytes: bytes) -> list[tuple[float, float]]:
    assert glb_bytes[:4] == b'glTF', 'Not a binary GLB'
    json_size, = struct.unpack_from('<I', glb_bytes, 12)
    gltf = json.loads(glb_bytes[20:20 + json_size])
    mesh = next(m for m in gltf['meshes'] if m.get('name') == 'HeadSkin')
    accessor = gltf['accessors'][mesh['primitives'][0]['attributes']['TEXCOORD_0']]
    assert accessor['componentType'] == 5126 and accessor['type'] == 'VEC2'
    view = gltf['bufferViews'][accessor['bufferView']]
    offset = 28 + json_size + view.get('byteOffset', 0) + accessor.get('byteOffset', 0)
    stride = view.get('byteStride', 8)
    return [struct.unpack_from('<ff', glb_bytes, offset + i * stride) for i in range(accessor['count'])]


def read_target(target_bytes: bytes) -> dict[int, tuple[float, float, float]]:
    result: dict[int, tuple[float, float, float]] = {}
    for line in decompress(target_bytes).decode('utf-8').splitlines():
        if not line or line.startswith('#'):
            continue
        i, dx, dy, dz = line.split()[:4]
        result[int(i)] = (float(dx), float(dy), float(dz))
    return result


def main() -> None:
    uv_source = source_vertex_for_uv(download('3dobjs/base.obj'))
    uvs = glb_head_uvs((ROOT / 'public/models/daz_asian_head_base.glb').read_bytes())
    matched = {
        vi: uv_source.get((round(u, 5), round(v, 5)))
        for vi, (u, v) in enumerate(uvs)
    }
    print(f'Head skin UV correspondence: {sum(v is not None for v in matched.values())}/{len(uvs)}')
    if sum(v is not None for v in matched.values()) < 3800:
        raise RuntimeError('Head topology / UVs changed; do not generate distorted morphs')

    output = [
        '// GENERATED by scripts/build_face_fine_targets.py from MakeHuman / MPFB2 CC0 sculpts.',
        '// Source: https://github.com/makehumancommunity/mpfb2/tree/3af0cd5a2ffba072e93a34e5f6f494fdc4813ddf/src/mpfb/data/targets',
        '// Original artist vertices are UV-projected to HeadSkin; [vertex, dx, dy, dz] in 1e-5 metres.',
        'export const FACE_FINE_TARGETS = Object.freeze({',
    ]
    for name, files in SOURCES.items():
        sculpt: dict[int, list[float]] = defaultdict(lambda: [0.0, 0.0, 0.0])
        for filename in files:
            for index, delta in read_target(download('targets/' + filename)).items():
                for axis in range(3):
                    sculpt[index][axis] += delta[axis]
        projected = []
        for vertex_index, source_index in sorted(matched.items()):
            if source_index not in sculpt:
                continue
            dx, dy, dz = (round(value * METRES_PER_UNIT * QUANTIZATION)
                          for value in sculpt[source_index])
            if dx or dy or dz:
                projected.extend([vertex_index, dx, dy, dz])
        if len(projected) < 100:
            raise RuntimeError(f'Suspiciously empty {name}: {len(projected)//4} vertices')
        output.append(f'  {json.dumps(name)}: [')
        for i in range(0, len(projected), 32):
            output.append('    ' + ', '.join(str(v) for v in projected[i:i + 32]) + ',')
        output.append('  ],')
        print(f'{name}: {len(projected)//4} sculpted head vertices')
    output.append('});')
    (ROOT / 'src/data/faceFineTargets.js').write_text('\n'.join(output) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
